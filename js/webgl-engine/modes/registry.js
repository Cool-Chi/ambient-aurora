/*
 * Background mode registry.
 *
 * Contract 1 - Persistence rule:
 *   A mode `id` string is persisted in user saves (localStorage, key `bgMode`).
 *   NEVER rename an existing `id`. If a mode is retired, delete its entry instead of renaming it.
 *
 * Contract 2 - Mode shader convention:
 *   Each mode's `glsl` snippet must define `vec3 render<Id>(vec2 uv, float u_time)`, where <Id> is the
 *   `id` with its first letter capitalized (e.g. `silk` -> `renderSilk`).
 *   Shared GLSL helpers available to every mode: hash(float), hash(vec2), noise(vec2), fbm(vec2).
 *   Uniforms available to every mode: u_color (vec3), u_color2 (vec3), u_resolution (vec2), u_octaves (int).
 *   Return value: un-exposed vec3 linear color (exposure scaling is applied by evalScene).
 *
 * Contract 3 - Mode GLSL restrictions (enforced by registerMode; a violating mode is rejected, others keep working):
 *   - `glsl` must not contain `#version`, `#define`, `uniform` or `precision` (the header is generated by shaders.js).
 *   - Top-level functions, constants and globals (and struct names) must be `render<Id>` or start with `<id>_`
 *     (case-insensitive), e.g. `silk_helper`, `SILK_SCALE`, and must not use a reserved shared name
 *     (hash, noise, fbm, pcg, pcg2d, evalScene, main, fragColor, MODE_COUNT and every shared uniform).
 *   - Line and block comments are ignored by these checks.
 *
 * Registration order defines the mode index (u_weights[i]). UI_CONFIG, the shader assembly and the engine
 * all read it from AA.MODES / AA.MODE_IDS / AA.MODE_INDEX_BY_ID; AA.nextMode(id) steps through it in order.
 */
(function (AA) {
  const modes = [];
  const modeIds = [];
  const modeIndexById = Object.create(null);

  const isNonEmptyString = v => typeof v === 'string' && v.length > 0;

  // Names owned by the shared shader assembly (shaders.js); a mode must never declare or shadow them
  const RESERVED_NAMES = new Set([
    'hash', 'noise', 'fbm', 'pcg', 'pcg2d', 'evalScene', 'main', 'fragColor', 'MODE_COUNT',
    'u_resolution', 'u_time', 'u_color', 'u_color2', 'u_weights', 'u_brightness',
    'u_time2', 'u_timeMix', 'u_vignette', 'u_octaves'
  ]);

  // Removes // and /* */ comments in a single pass (GLSL has no string literals)
  function stripGlslComments(src) {
    let out = '';
    let i = 0;
    while (i < src.length) {
      const c = src[i];
      const n = src[i + 1];
      if (c === '/' && n === '/') {
        while (i < src.length && src[i] !== '\n') i++;
      } else if (c === '/' && n === '*') {
        const end = src.indexOf('*/', i + 2);
        i = end === -1 ? src.length : end + 2;
        out += ' ';
      } else {
        out += c;
        i++;
      }
    }
    return out;
  }

  // Names declared at brace depth 0: [{ kind: 'function' | 'variable' | 'struct', name }]; null if braces are unbalanced
  function scanTopLevelDecls(code) {
    const decls = [];
    let depth = 0;
    let seg = '';
    let fnBody = false;

    const splitDeclarators = text => {
      const parts = [];
      let level = 0;
      let cur = '';
      for (const ch of text) {
        if (ch === '(' || ch === '[') level++;
        else if (ch === ')' || ch === ']') level--;
        if (ch === ',' && level === 0) {
          parts.push(cur);
          cur = '';
        } else {
          cur += ch;
        }
      }
      parts.push(cur);
      return parts;
    };

    const lastIdent = text => {
      const m = /([A-Za-z_]\w*)\s*$/.exec(text.replace(/\[[^\]]*\]/g, ''));
      return m ? m[1] : '';
    };

    const flush = () => {
      const s = seg.trim();
      seg = '';
      if (!s) return;
      const sm = /^struct\s+([A-Za-z_]\w*)/.exec(s);
      if (sm) {
        decls.push({ kind: 'struct', name: sm[1] });
        const close = s.lastIndexOf('}');
        const tail = close === -1 ? '' : s.slice(close + 1);
        if (tail.trim()) {
          splitDeclarators(tail).forEach(p => {
            const n = lastIdent(p);
            if (n) decls.push({ kind: 'variable', name: n });
          });
        }
        return;
      }
      const eq = s.indexOf('=');
      const par = s.indexOf('(');
      if (par !== -1 && (eq === -1 || par < eq)) {
        const n = lastIdent(s.slice(0, par));
        if (n) decls.push({ kind: 'function', name: n });
        return;
      }
      splitDeclarators(s).forEach(p => {
        const e = p.indexOf('=');
        const n = lastIdent(e === -1 ? p : p.slice(0, e));
        if (n) decls.push({ kind: 'variable', name: n });
      });
    };

    for (let i = 0; i < code.length; i++) {
      const ch = code[i];
      if (ch === '{') {
        if (depth === 0) {
          fnBody = seg.trimEnd().endsWith(')');
          seg += '{';
        }
        depth++;
      } else if (ch === '}') {
        depth--;
        if (depth < 0) return null;
        if (depth === 0) {
          seg += '}';
          if (fnBody) {
            flush();
            fnBody = false;
          }
        }
      } else if (depth === 0) {
        if (ch === ';') flush();
        else seg += ch;
      }
    }
    if (depth !== 0) return null;
    flush();
    return decls;
  }

  // Returns a rejection reason, or '' when the mode glsl is acceptable
  function checkGlsl(def, fnName, sig) {
    const code = stripGlslComments(def.glsl);
    if (/#\s*version\b/.test(code)) return 'glsl must not contain "#version" (the shader header is generated by shaders.js)';
    if (/#\s*define\b/.test(code)) return 'glsl must not contain "#define" (use const declarations named with the "' + def.id + '_" prefix)';
    if (/\buniform\b/.test(code)) return 'glsl must not declare "uniform" (shared uniforms are provided by the engine)';
    if (/\bprecision\b/.test(code)) return 'glsl must not contain "precision" (precision is set by the shader header)';
    if (!sig.test(code)) return `glsl must define "vec3 ${fnName}(vec2 uv, float u_time)" outside of comments`;

    const body = code.replace(/^[ \t]*#.*$/gm, '');
    const decls = scanTopLevelDecls(body);
    if (!decls) return 'unbalanced braces in glsl';
    const prefix = new RegExp('^' + def.id + '_', 'i');
    for (const d of decls) {
      if (RESERVED_NAMES.has(d.name)) return `top-level ${d.kind} "${d.name}" collides with a reserved shared name`;
      if (d.name !== fnName && !prefix.test(d.name)) {
        return `top-level ${d.kind} "${d.name}" must be named "${fnName}" or start with "${def.id}_"`;
      }
    }

    // Typed declarations anywhere (locals, parameters) must not shadow shared names; the entry
    // signature's own `float u_time` parameter is the only allowed use of a reserved name
    const declRe = /\b(?:float|int|uint|bool|[iub]?vec[234]|mat[234](?:x[234])?|struct)\s+([A-Za-z_]\w*)/g;
    let m;
    while ((m = declRe.exec(body))) {
      if (RESERVED_NAMES.has(m[1]) && m[1] !== 'u_time') return `identifier "${m[1]}" shadows a reserved shared name`;
    }
    return '';
  }

  function registerMode(def) {
    const fail = reason => {
      console.error('[AA.registerMode] Invalid mode definition:', reason, def);
      return false;
    };

    if (!def || typeof def !== 'object') return fail('definition must be an object');
    if (typeof def.id !== 'string' || !/^[a-z][a-z0-9]*$/.test(def.id)) {
      return fail('id must be a non-empty lowercase string matching /^[a-z][a-z0-9]*$/');
    }
    if (!def.label || typeof def.label !== 'object' || !isNonEmptyString(def.label.en) || !isNonEmptyString(def.label.zh)) {
      return fail('label must be an object with non-empty label.en and label.zh');
    }
    if (typeof def.exposure !== 'number' || !Number.isFinite(def.exposure) || !(def.exposure > 0)) {
      return fail('exposure must be a finite positive number');
    }
    if (!isNonEmptyString(def.glsl)) return fail('glsl must be a non-empty string');
    if (def.id in modeIndexById) return fail(`id "${def.id}" is already registered`);

    const fnName = 'render' + def.id[0].toUpperCase() + def.id.slice(1);
    const sig = new RegExp('\\bvec3\\s+' + fnName + '\\s*\\(\\s*vec2\\s+uv\\s*,\\s*float\\s+u_time\\s*\\)');
    if (!sig.test(def.glsl)) {
      return fail(`glsl must define "vec3 ${fnName}(vec2 uv, float u_time)"`);
    }

    const glslIssue = checkGlsl(def, fnName, sig);
    if (glslIssue) {
      console.error('[AA.registerMode] Rejected mode "' + (def && def.id) + '": ' + glslIssue);
      return false;
    }

    const entry = Object.freeze({
      id: def.id,
      fnName,
      expConst: 'EXP_' + def.id.toUpperCase(),
      label: Object.freeze({ en: def.label.en, zh: def.label.zh }),
      exposure: def.exposure,
      glsl: def.glsl.trim()
    });
    modeIndexById[def.id] = modes.length;
    modes.push(entry);
    modeIds.push(def.id);
    return true;
  }

  // Next mode id in registration order, wrapping from the last entry back to the first
  function nextMode(currentId) {
    const count = modeIds.length;
    if (count === 0) return '';
    if (count === 1) return modeIds[0];
    if (!(currentId in modeIndexById)) return modeIds[0];
    return modeIds[(modeIndexById[currentId] + 1) % count];
  }

  AA.registerMode = registerMode;
  AA.nextMode = nextMode;
  Object.defineProperties(AA, {
    MODES: { get: () => modes, enumerable: true, configurable: true },
    MODE_IDS: { get: () => modeIds, enumerable: true, configurable: true },
    MODE_INDEX_BY_ID: { get: () => modeIndexById, enumerable: true, configurable: true }
  });
})(window.AA);
